/** Normaliza para busca sem acento/caixa. */
export function normalizarBusca(s: string): string {
  return s.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
}

/**
 * Busca de templates para o autocomplete: casa por nome do modelo, favorecido,
 * razão social ou documento (CNPJ/CPF), sem acento e em qualquer posição.
 */
export function buscarTemplates(q: string, limite = 12): TermoFornecedorTemplate[] {
  const termos = normalizarBusca(q.trim()).split(/\s+/).filter(Boolean);
  if (termos.length === 0) return TERMO_TEMPLATES.slice(0, limite);
  const alvo = (t: TermoFornecedorTemplate) =>
    normalizarBusca(`${t.nome} ${t.favorecido} ${t.destinatario.razao_social} ${t.destinatario.documento}`);
  return TERMO_TEMPLATES
    .filter((t) => { const a = alvo(t); return termos.every((x) => a.includes(x)); })
    .slice(0, limite);
}
